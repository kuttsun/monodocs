/**
 * RFC 5646 の grandfathered タグ（irregular と regular）。BCP 47 として妥当だが、
 * `Intl.getCanonicalLocales` は Unicode の locale identifier 文法で見るため大半を弾く。
 * ここで先に受けないと、`lang: i-klingon` の文書がビルドできなくなる。
 * レジストリ上は追加されない固定の集合なので、列挙で足りる。
 */
const GRANDFATHERED = new Set(
  [
    "en-GB-oed",
    "i-ami",
    "i-bnn",
    "i-default",
    "i-enochian",
    "i-hak",
    "i-klingon",
    "i-lux",
    "i-mingo",
    "i-navajo",
    "i-pwn",
    "i-tao",
    "i-tay",
    "i-tsu",
    "sgn-BE-FR",
    "sgn-BE-NL",
    "sgn-CH-DE",
    "art-lojban",
    "cel-gaulish",
    "no-bok",
    "no-nyn",
    "zh-guoyu",
    "zh-hakka",
    "zh-min",
    "zh-min-nan",
    "zh-xiang",
  ].map((tag) => tag.toLowerCase()),
);

/**
 * 構文的に妥当な BCP 47 言語タグか。
 *
 * 文書の言語であり `<html lang>` はそれを表明できなければならないので、「タグとして妥当か」
 * だけを見る。妥当でない文字列は属性に書かず拒否する。
 *
 * 判定の主体は `Intl.getCanonicalLocales`（well-formed でなければ RangeError を投げる）だが、
 * これは Unicode の locale identifier 文法なので BCP 47 と完全には一致しない。妥当なのに
 * 弾かれる 2 種類 — 私用のみのタグと grandfathered タグ — を先に受ける。
 */
export function isValidLanguageTag(tag: string): boolean {
  if (tag.length === 0 || tag.length > 100) return false;
  if (GRANDFATHERED.has(tag.toLowerCase())) return true;
  // 私用のみのタグ（x-pig-latin など）。
  if (/^x(-[A-Za-z0-9]{1,8})+$/i.test(tag)) return true;
  try {
    Intl.getCanonicalLocales(tag);
    return true;
  } catch {
    return false;
  }
}

/**
 * 英語の表に `overrides` を重ねる。`lang` は見ない。表を選ばないので、どのタグでも警告は出ない。
 */
export function resolveLabels(overrides: Partial<Labels> = {}): Labels {
  return { ...DEFAULT_LABELS, ...overrides };
}
