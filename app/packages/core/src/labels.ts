/**
 * 同梱する表。**en と ja だけ**にとどめる。中途半端に訳した言語を core に同梱するのは、
 * その言語の読者にとって何も無いより悪く、しかも保守するのは話者ではなく維持者になる。
 * 他の言語は `html.labels` で入れられる。
 */
const TABLES: Record<string, Labels> = { en: EN, ja: JA };
const DIFF_TABLES: Record<string, DiffLabels> = { en: DIFF_EN, ja: DIFF_JA };

export const DEFAULT_LANG = "en";

/**
 * RFC 5646 の grandfathered タグ（irregular と regular）。BCP 47 として妥当だが、
 * `Intl.getCanonicalLocales` は Unicode の locale identifier 文法で見るため大半を弾く。
 * ここで先に受けないと、`lang: i-klingon` の文書がビルドできなくなる。
 * レジストリ上は追加されない固定の集合なので、列挙で足りる。
 */
const GRANDFATHERED = new Set(
  [
    "en-GB-oed",
    "i-ami",
    "i-bnn",
    "i-default",
    "i-enochian",
    "i-hak",
    "i-klingon",
    "i-lux",
    "i-mingo",
    "i-navajo",
    "i-pwn",
    "i-tao",
    "i-tay",
    "i-tsu",
    "sgn-BE-FR",
    "sgn-BE-NL",
    "sgn-CH-DE",
    "art-lojban",
    "cel-gaulish",
    "no-bok",
    "no-nyn",
    "zh-guoyu",
    "zh-hakka",
    "zh-min",
    "zh-min-nan",
    "zh-xiang",
  ].map((tag) => tag.toLowerCase()),
);

/**
 * 構文的に妥当な BCP 47 言語タグか。
 *
 * 文書の言語であり `<html lang>` はそれを表明できなければならないので、同梱の表があるかとは
 * 無関係に「タグとして妥当か」だけを見る。妥当でない文字列は属性に書かず拒否する。
 *
 * 判定の主体は `Intl.getCanonicalLocales`（well-formed でなければ RangeError を投げる）だが、
 * これは Unicode の locale identifier 文法なので BCP 47 と完全には一致しない。妥当なのに
 * 弾かれる 2 種類 — 私用のみのタグと grandfathered タグ — を先に受ける。どちらも同梱の表は
 * 無いのでラベルは英語へ落ちるが、それは属性に書けないこととは別の話である。
 */
export function isValidLanguageTag(tag: string): boolean {
  if (tag.length === 0 || tag.length > 100) return false;
  if (GRANDFATHERED.has(tag.toLowerCase())) return true;
  // 私用のみのタグ（x-pig-latin など）。
  if (/^x(-[A-Za-z0-9]{1,8})+$/i.test(tag)) return true;
  try {
    Intl.getCanonicalLocales(tag);
    return true;
  } catch {
    return false;
  }
}

/**
 * タグから同梱の表を探すためのキー（主言語サブタグを小文字化したもの）。
 * `en-GB` / `ja-JP` / `JA` はいずれも表に行き着く。照合先の無いタグ
 * （私用のみのタグ、grandfathered タグ）は undefined を返す。
 */
function primarySubtag(tag: string): string | undefined {
  const first = tag.split("-")[0]?.toLowerCase();
  if (first === undefined || first === "" || first === "x") return undefined;
  // 主言語サブタグは 2〜3 文字（または 4〜8 文字の登録済み言語）。数字を含むものは
  // 主言語サブタグではない。
  return /^[a-z]{2,8}$/.test(first) ? first : undefined;
}

export type ResolvedLabels = {
  labels: Labels;
  /** The finding reported when no shipped table matched and English was used instead. */
  warning?: Diagnostic;
};

/**
 * `lang` に対する表を選び、`overrides` をその上に重ねる。
 *
 * 同梱の表が無いタグは拒否せず en の表へ落として警告する。拒否すると、フランス語の文書が
 * ビルドを通すためだけに自分を英語だと偽ることになり、上書きできる英語ラベルより読者にとって
 * 悪い。警告はビルド 1 回につき 1 度、タグ名を挙げて出す（呼び出し側が 1 回だけ呼ぶ）。
 */
export function resolveLabels(lang: string, overrides: LabelOverrides = {}): ResolvedLabels {
  const key = primarySubtag(lang);
  const table = key === undefined ? undefined : TABLES[key];
  // Only the main table's keys: a difference's labels never reach a build without one.
  const own = Object.fromEntries(
    Object.entries(overrides).filter(([name]) => (LABEL_KEYS as readonly string[]).includes(name)),
  ) as Partial<Labels>;
  const labels = { ...(table ?? EN), ...own };
  if (table !== undefined) return { labels };
  return {
    labels,
    warning: warn(
      "lang/no-label-table",
      t("labels.noTable", {
        lang,
        fallback: DEFAULT_LANG,
        shipped: Object.keys(TABLES).join(", "),
      }),
    ),
  };
}

/**
 * A difference's labels for `lang`, with `overrides` laid over them. A tag with no shipped table
 * falls back to English, as {@link resolveLabels} does and reports once for the build.
 */
export function resolveDiffLabels(lang: string, overrides: LabelOverrides = {}): DiffLabels {
  const key = primarySubtag(lang);
  const table = (key === undefined ? undefined : DIFF_TABLES[key]) ?? DIFF_EN;
  const own = Object.fromEntries(
    Object.entries(overrides).filter(([name]) =>
      (DIFF_LABEL_KEYS as readonly string[]).includes(name),
    ),
  ) as Partial<DiffLabels>;
  return { ...table, ...own };
}
