/**
 * monodocs 自身が出すメッセージのカタログ。
 *
 * `--help`、エラー、警告のすべてがここを通る。既定は英語で、日本語は明示的に選ぶ
 * （`--lang ja` / `MONODOCS_LANG=ja`）。README・ドキュメントサイト・CONTRIBUTING・SECURITY が
 * 英語を既定に日本語を併記しているのに、CLI だけ日本語しか出さないのは、npm 経由で届く読者の
 * 大半に対して不親切だった。
 *
 * **文書の `lang`（23.4）とは別物。** あちらはビルドされるページを記述し、こちらはビルドしている
 * 端末を記述する。文書がある言語で書かれ、書いている人の端末が別の言語を返すことはよくある。
 *
 * **`LANG` / `LC_ALL` は意図的に見ない。** 自動検出は便利だが、ビルドログがどのマシンで作られたかに
 * 依存することになり、issue に貼られたログをコマンドだけからは再現できなくなる。明示指定の
 * 一度きりの手間のほうが安い。
 *
 * ## 境界
 *
 * 対象は monodocs が印字前に手にしている文字列である。依存パッケージのメッセージが包まれずに
 * そのまま利用者へ届くもの（Zod のパースエラー本体、Puppeteer のスタック）は対象外。monodocs が
 * すでに包んでいるものは、その包み側を訳す。
 */

