const CATALOGUES: Record<MessageLang, Record<MessageKey, string>> = { en: EN, ja: JA };

let current: MessageLang = DEFAULT_MESSAGE_LANG;

/**
 * 以降のメッセージの言語を決める。CLI が起動時に 1 度だけ呼ぶ。
 * ライブラリとして使う場合は呼ばなければ英語のままになる。
 */
export function setMessageLang(lang: MessageLang): void {
  current = lang;
}

export function getMessageLang(): MessageLang {
  return current;
}

/**
 * `--lang` と `MONODOCS_LANG` から言語を決める。フラグ > 環境変数 > 既定。
 * 対応しない値は、黙ってフォールバックせず対応する値を挙げて拒否する（指定したのに効いていない、
 * という最も気づきにくい失敗にしない）。
 */
export function resolveMessageLang(options: { flag?: string; env?: string }): MessageLang {
  // フラグは「無い」と「空で指定された」を区別する。空を既定へ落とすと、`--lang=` が
  // 環境変数まで打ち消したうえで黙って英語になり、優先順位も未対応値の拒否も破れる。
  // 環境変数の空文字は「未設定」として扱う（シェルではそれが通例）。
  const value = options.flag ?? (options.env === "" ? undefined : options.env);
  if (value === undefined) return DEFAULT_MESSAGE_LANG;
  const found = MESSAGE_LANGS.find((lang) => lang === value.toLowerCase());
  if (found) return found;
  // ここだけは翻訳前に出す必要がある（どの言語を使うかを決めている最中なので）。
  throw new Error(
    format(EN["config.unsupportedMessageLang"], {
      value,
      supported: MESSAGE_LANGS.join(", "),
    }),
  );
}

/** `{name}` を差し替える。値が無いプレースホルダはそのまま残す（消すと文が壊れる）。 */
function format(template: string, params: Record<string, string | number> = {}): string {
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match,
  );
}

/** 現在の言語でメッセージを組み立てる。 */
export function t(key: MessageKey, params: Record<string, string | number> = {}): string {
  return format(CATALOGUES[current][key], params);
}

