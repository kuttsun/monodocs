import { describe, expect, it } from "vitest";
import {
  DIFF_LABEL_KEYS,
  isValidLanguageTag,
  LABEL_KEYS,
  resolveDiffLabels,
  resolveLabels,
} from "./labels";

describe("isValidLanguageTag", () => {
  it("accepts tags a document may legitimately declare", () => {
    // 同梱の表があるかとは無関係。`<html lang>` は文書の言語を表明できなければならない。
    for (const tag of ["en", "ja", "en-GB", "ja-JP", "fr", "zh-Hant-TW", "de-CH-1901", "x-pig"]) {
      expect(isValidLanguageTag(tag), tag).toBe(true);
    }
  });

  it("accepts grandfathered tags, which the Intl grammar rejects", () => {
    // BCP 47 としては妥当なのに Intl.getCanonicalLocales は投げる。ここを任せきりにすると、
    // lang: i-klingon の文書がビルドできない。
    for (const tag of ["i-klingon", "en-GB-oed", "sgn-BE-FR", "zh-min-nan", "I-NAVAJO"]) {
      expect(isValidLanguageTag(tag), tag).toBe(true);
    }
  });

  it("rejects what is not a language tag, rather than writing it into the attribute", () => {
    for (const tag of ["", "e", "english!", "en_US", "日本語", "en-", "-en", "a".repeat(101)]) {
      expect(isValidLanguageTag(tag), tag).toBe(false);
    }
  });
});

describe("resolveLabels", () => {
  it("ships a complete table for every language it claims to ship", () => {
    for (const lang of ["en", "ja"]) {
      const { labels, warning } = resolveLabels(lang);
      expect(warning).toBeUndefined();
      // 半分だけ訳された表は、その言語の読者にとって表が無いより悪い。
      for (const key of LABEL_KEYS) {
        expect(labels[key], `${lang}.${key}`).toBeTruthy();
      }
    }
  });

  it("gives a Japanese document Japanese labels", () => {
    expect(resolveLabels("ja").labels.tocTitle).toBe("このページの内容");
    expect(resolveLabels("en").labels.tocTitle).toBe("On this page");
  });

  it("matches on the primary subtag, case-insensitively", () => {
    for (const tag of ["ja-JP", "JA", "ja-Jpan-JP"]) {
      expect(resolveLabels(tag).labels.tocTitle, tag).toBe("このページの内容");
      expect(resolveLabels(tag).warning, tag).toBeUndefined();
    }
    expect(resolveLabels("en-GB").labels.tocTitle).toBe("On this page");
  });

  it("falls back to English and warns, naming the tag, rather than rejecting the document", () => {
    // 拒否すると、フランス語の文書がビルドを通すためだけに自分を英語だと偽ることになる。
    const { labels, warning } = resolveLabels("fr");
    expect(labels.tocTitle).toBe("On this page");
    expect(warning?.message).toContain('"fr"');
    expect(warning?.message).toContain("en");
  });

  it("falls back for a tag that has no primary subtag to match", () => {
    // 私用のみのタグにも grandfathered の i-* にも、照合先の主言語サブタグが無い。
    expect(resolveLabels("x-klingon").warning?.message).toContain("x-klingon");
    expect(resolveLabels("i-klingon").warning?.message).toContain("i-klingon");
    // 主言語サブタグはあるが表が無いもの。ここも同じ扱い。
    expect(resolveLabels("sgn-BE-FR").warning?.message).toContain("sgn-BE-FR");
  });

  it("applies overrides on top of the chosen table, leaving the rest of it alone", () => {
    const { labels } = resolveLabels("ja", { tocTitle: "目次", copy: "複製" });
    expect(labels.tocTitle).toBe("目次");
    expect(labels.copy).toBe("複製");
    // 差し替えたのは 2 つだけ。残りは ja の表のまま。
    expect(labels.noResults).toBe("該当なし");
  });

  it("applies overrides on top of the fallback table too", () => {
    const { labels, warning } = resolveLabels("fr", { tocTitle: "Sur cette page" });
    expect(labels.tocTitle).toBe("Sur cette page");
    expect(labels.noResults).toBe("No results");
    // 上書きしても、表が無いこと自体は伝える（他のラベルは英語のままなので）。
    expect(warning).toBeDefined();
  });

  it("leaves generatedBy English in the ja table, and marks it English only there", () => {
    // The footer reads "Generated by monodocs v…" in every language: a label holds no placeholder,
    // so no Japanese phrase can sit in front of the link in the order Japanese wants (#224, 23.4).
    const ja = resolveLabels("ja");
    expect(ja.labels.generatedBy).toBe("Generated by");
    expect(ja.generatorInEnglish).toBe(true);
    expect(resolveLabels("ja-JP").generatorInEnglish).toBe(true);
    // The whole chrome is English under en and under the fallback: nothing to mark apart.
    expect(resolveLabels("en").generatorInEnglish).toBe(false);
    expect(resolveLabels("fr").generatorInEnglish).toBe(false);
    // An author who sets it says which language it is in; any wording, even the English one.
    for (const generatedBy of ["作成ツール:", "Generated by"]) {
      const own = resolveLabels("ja", { generatedBy });
      expect(own.labels.generatedBy).toBe(generatedBy);
      expect(own.generatorInEnglish, generatedBy).toBe(false);
    }
  });

  it("takes only the main table's keys from the overrides", () => {
    const { labels } = resolveLabels("ja", { diffChanges: "差分" });
    expect(Object.keys(labels)).toEqual([...LABEL_KEYS]);
  });
});

describe("resolveDiffLabels", () => {
  it("ships a complete difference table for every language it claims to ship", () => {
    for (const lang of ["en", "ja"]) {
      const labels = resolveDiffLabels(lang);
      expect(Object.keys(labels), lang).toEqual([...DIFF_LABEL_KEYS]);
      for (const key of DIFF_LABEL_KEYS) expect(labels[key], `${lang}.${key}`).toBeTruthy();
    }
  });

  it("selects the table as resolveLabels does, and lays overrides over it", () => {
    for (const tag of ["ja", "ja-JP", "JA"]) {
      expect(resolveDiffLabels(tag).diffChanges, tag).toBe("変更点");
    }
    expect(resolveDiffLabels("en-GB").diffChanges).toBe("Changes");
    expect(resolveDiffLabels("fr").diffChanges).toBe("Changes");
    expect(resolveDiffLabels("x-klingon").diffChanges).toBe("Changes");
    const own = resolveDiffLabels("ja", { diffChanges: "差分", tocTitle: "目次" });
    expect(own.diffChanges).toBe("差分");
    expect(own.diffNext).toBe("次の変更");
    expect(Object.keys(own)).toEqual([...DIFF_LABEL_KEYS]);
  });
});
