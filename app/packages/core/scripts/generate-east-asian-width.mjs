// Generates src/sources/eastAsianWidth.ts from the vendored Unicode EastAsianWidth.txt.
//
// JavaScript regular expressions expose `\p{Script=Han}` but not `\p{East_Asian_Width=W}`, so the
// code points whose width is F, W, or H are written out as a table (roadmap 12.6).
//
//   node scripts/generate-east-asian-width.mjs           rewrite the table
//   node scripts/generate-east-asian-width.mjs --check   exit 1 if the table does not match the data
//
// To move to a new Unicode version, put its EastAsianWidth.txt in scripts/data/ under its
// versioned name, point DATA_FILE at it, delete the old one, and run without --check.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const DATA_FILE = new URL("./data/EastAsianWidth-18.0.0.txt", import.meta.url);
const TABLE_FILE = new URL("../src/sources/eastAsianWidth.ts", import.meta.url);
const WIDE = new Set(["F", "W", "H"]);

/** Parses the data file into the version it declares and merged [start, end] ranges of F/W/H. */
export function parse(text) {
  const version = /^# EastAsianWidth-(\d+\.\d+\.\d+)\.txt$/m.exec(text)?.[1];
  if (!version) throw new Error("EastAsianWidth.txt: no version line");
  const copyright = /^# (© \d{4} Unicode®, Inc\.)$/m.exec(text)?.[1];
  if (!copyright) throw new Error("EastAsianWidth.txt: no copyright line");
  // The defaults below are prose in the header, not data. Refuse a file whose prose no longer
  // names exactly these ranges, so an upgrade cannot carry stale defaults past --check.
  const named = [...text.matchAll(/^#\s+[^\n]*?U\+([0-9A-F]+)\.\.U\+([0-9A-F]+)\s*$/gm)].map(
    (m) => `${m[1]}..${m[2]}`,
  );
  const expected = ["3400..4DBF", "4E00..9FFF", "F900..FAFF", "20000..2FFFD", "30000..3FFFD"];
  if (named.join(",") !== expected.join(",")) {
    throw new Error(`EastAsianWidth.txt: default "W" ranges changed: ${named.join(", ")}`);
  }

  const width = new Map();
  const assign = (start, end, value) => {
    for (let cp = start; cp <= end; cp++) width.set(cp, value);
  };
  // Defaults the file states in its header for code points it does not list. They are applied
  // first so that every explicit line overrides them.
  assign(0x3400, 0x4dbf, "W");
  assign(0x4e00, 0x9fff, "W");
  assign(0xf900, 0xfaff, "W");
  assign(0x20000, 0x2fffd, "W");
  assign(0x30000, 0x3fffd, "W");

  for (const line of text.split("\n")) {
    const data = line.replace(/#.*/, "").trim();
    if (!data) continue;
    const m = /^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)$/.exec(data);
    if (!m) throw new Error(`EastAsianWidth.txt: cannot read ${JSON.stringify(line)}`);
    const start = parseInt(m[1], 16);
    assign(start, m[2] ? parseInt(m[2], 16) : start, m[3]);
  }

  const ranges = [];
  const points = [...width.entries()].filter(([, v]) => WIDE.has(v)).map(([cp]) => cp);
  points.sort((a, b) => a - b);
  for (const cp of points) {
    const last = ranges[ranges.length - 1];
    if (last && last[1] === cp - 1) last[1] = cp;
    else ranges.push([cp, cp]);
  }
  return { version, copyright, ranges };
}

function hex(cp) {
  return "0x" + cp.toString(16).toUpperCase().padStart(4, "0");
}

/** Renders the TypeScript module, one range per row. */
export function render({ version, copyright, ranges }) {
  const rows = ranges.map(([s, e]) => `  ${hex(s)}, ${hex(e)},`).join("\n");
  return `/*!
 * East_Asian_Width F, W, and H ranges, derived from the Unicode Character Database.
 * ${copyright} Distributed under the Unicode License v3, reproduced in
 * scripts/data/LICENSE-Unicode.txt and in the distribution's THIRD-PARTY-NOTICES.txt.
 */
// Generated by scripts/generate-east-asian-width.mjs from EastAsianWidth-${version}.txt. Do not edit;
// a test fails when this file and the data file disagree.

/** The Unicode version the table was generated from. */
export const EAST_ASIAN_WIDTH_UNICODE_VERSION = "${version}";

/** Sorted, non-overlapping inclusive ranges, flattened as [start, end, start, end, …]. */
// prettier-ignore
export const EAST_ASIAN_WIDE_RANGES: readonly number[] = [
${rows}
];
`;
}

async function main() {
  const text = await readFile(DATA_FILE, "utf8");
  const expected = render(parse(text));
  if (process.argv.includes("--check")) {
    const actual = await readFile(TABLE_FILE, "utf8").catch(() => "");
    if (actual !== expected) {
      console.error("src/sources/eastAsianWidth.ts does not match the data file; regenerate it.");
      process.exit(1);
    }
    return;
  }
  await writeFile(TABLE_FILE, expected, "utf8");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
